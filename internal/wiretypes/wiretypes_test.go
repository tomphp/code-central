// The fixtures: small Go types, one or two per mapping rule.

// Base is embedded by Row.
type Base struct {
	ID string `json:"id"`
}

// Other is embedded by Row too.
type Other struct {
	Note string `json:"note"`
}

// Row embeds two structs.
type Row struct {
	Base
	Other
	Count int `json:"count"`
}

type Optional struct {
	Empty   string     `json:"empty,omitempty"`
	Zero    Base       `json:"zero,omitzero"`
	Pointer *int       `json:"pointer"`
	When    *time.Time `json:"when,omitempty"`
	Plain   bool       `json:"plain"`
}

type Slices struct {
	Tags   []string `json:"tags"`
	Labels []string `json:"labels,omitempty"`
	Rows   []Base   `json:"rows,omitzero"`
}

type Times struct {
	Created time.Time `json:"created"`
}

// Color is a typed string with a value list.
type Color string

// The Colors, declared out of list order.
const (
	Green Color = "green"
	Red   Color = "red"
	Blue  Color = "blue"
)

// Colors are the Colors in the order the UI shows them.
var Colors = []Color{Red, Green, Blue}

type Maps struct {
	Counts map[string]int  `json:"counts"`
	Shown  map[Color]bool  `json:"shown"`
	Hex    map[Color]Base  `json:"hex,omitempty"`
	Ages   map[int]float64 `json:"ages"`
}

type Painted struct {
	Color  Color   `json:"color"`
	Others []Color `json:"others"`
}

// Shade is a typed string with no value list.
type Shade string

type Palette struct {
	Name  string `json:"name"`
	Shade Shade  `json:"shade"`
}

// Size is a typed string whose value list misses one of its constants.
type Size string

const (
	Small  Size = "small"
	Medium Size = "medium"
	Large  Size = "large"
)

var Sizes = []Size{Small, Large}

// Custom has its own JSON encoding.
type Custom struct{}

func (Custom) MarshalJSON() ([]byte, error) { return []byte(`"custom"`), nil }

type HasCustom struct {
	Custom Custom `json:"custom"`
}

// Named is a struct whose JSON names come from its tags.
type Named struct {
	// Tagged has a JSON name.
	Tagged string `json:"tagged"`
	// Untagged has none, so its Go name is its JSON name.
	Untagged string
	Skipped  string `json:"-"`
	hidden   string
	// Level is a named basic type that isn't a string.
	Level Level `json:"level"`
	// Raw is any JSON at all.
	Raw json.RawMessage `json:"raw"`
	// Bytes is base64.
	Bytes []byte `json:"bytes"`
	// Pair is an array.
	Pair [2]int `json:"pair"`
}

// Level is a number.
type Level int

func generate(t *testing.T, roots []reflect.Type, enums ...Enum) string {
	t.Helper()
	out, err := Generate(roots, enums)
	if err != nil {
		t.Fatalf("Generate: %v", err)
	}
	return out
}

func contains(t *testing.T, out string, want ...string) {
	t.Helper()
	for _, w := range want {
		if !strings.Contains(out, w) {
			t.Errorf("the output lacks\n%s\n--- output:\n%s", w, out)
		}
	}
}

func fails(t *testing.T, roots []reflect.Type, enums []Enum, want ...string) {
	t.Helper()
	out, err := Generate(roots, enums)
	if err == nil {
		t.Fatalf("Generate succeeded, want an error; output:\n%s", out)
	}
	for _, w := range want {
		if !strings.Contains(err.Error(), w) {
			t.Errorf("the error %q doesn't name %q", err, w)
		}
	}
}

var colors = enumOf("Colors", Colors)

func TestTheHeaderSaysTheFileIsGenerated(t *testing.T) {
	out := generate(t, []reflect.Type{reflect.TypeFor[Base]()})
	if !strings.HasPrefix(out, "// Code generated by `make wiretypes` from the Core's Go types. DO NOT EDIT.\n") {
		t.Errorf("the output doesn't start with the generated header:\n%s", out)
	}
}

func TestAnEmbeddedStructIsExtended(t *testing.T) {
	out := generate(t, []reflect.Type{reflect.TypeFor[Row]()})
	contains(t, out,
		"export interface Row extends Base, Other {\n  count: number;\n}\n",
		"export interface Base {\n  id: string;\n}\n",
		"export interface Other {\n  note: string;\n}\n",
	)
}

func TestOmitemptyOmitzeroAndPointersAreOptional(t *testing.T) {
	out := generate(t, []reflect.Type{reflect.TypeFor[Optional]()})
	contains(t, out, "export interface Optional {\n"+
		"  empty?: string;\n"+
		"  zero?: Base;\n"+
		"  pointer?: number;\n"+
		"  when?: string;\n"+
		"  plain: boolean;\n"+
		"}\n")
	if strings.Contains(out, "null") {
		t.Errorf("a pointer became nullable:\n%s", out)
	}
}

