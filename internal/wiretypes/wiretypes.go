// Command wiretypes writes the UI's wire types (Spec code-central-718,
// ADR 0042): the TypeScript the UI reads the HTTP API's responses as,
// generated from the Core's Go view types for `make wiretypes`. Shapes
// come from reflection over the root types in roots.go and every type
// they reach, with JSON names as the Core's JSONNames reads them; doc
// comments come from the Go source. Each typed string the roots reach
// is a union with its value array, from the Go value list registered
// beside the roots. Each record view registered there for a field list,
// such as TICKET_FIELDS, gives an array of the JSON names a write's
// changed lists. It uses only the standard library and, like
// internal/corewasm, is a developer tool for the Makefile, not a
// shipped command.
//
//	go run ./internal/wiretypes web/src/api/wire.gen.ts
package main

import (
	"bytes"
	"encoding"
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"reflect"
	"slices"
	"strings"
	"time"
	"unicode"

	"github.com/tomoram/code-central/core"
)

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: wiretypes <file>")
		os.Exit(2)
	}
	text, err := Generate(roots, enums, fields)
	if err != nil {
		fmt.Fprintln(os.Stderr, "wiretypes:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(os.Args[1], []byte(text), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "wiretypes:", err)
		os.Exit(1)
	}
}

// Enum ties a typed string the UI reaches to its Go value list.
type Enum struct {
	// Type is the typed string, such as store.State.
	Type reflect.Type
	// List is the value list's Go name, such as "States". Its
	// SCREAMING_SNAKE_CASE form names the TypeScript value array.
	List string
	// Values are the value list's values, in its order.
	Values []string
}

// enumOf is the Enum for a value list of its own typed string.
func enumOf[T ~string](list string, values []T) Enum {
	out := make([]string, len(values))
	for i, v := range values {
		out[i] = string(v)
	}
	return Enum{Type: reflect.TypeFor[T](), List: list, Values: out}
}

// Fields names a record view whose JSON names the UI lists: a write's
// Acknowledgement names the fields it changed by them.
type Fields struct {
	// Type is the view, such as core.TicketView.
	Type reflect.Type
	// List is the list's name, such as "TicketFields". Its
	// SCREAMING_SNAKE_CASE form names the TypeScript array.
	List string
}

// fieldsOf is the Fields for view T.
func fieldsOf[T any](list string) Fields {
	return Fields{Type: reflect.TypeFor[T](), List: list}
}

// header starts the generated file; its first line is Go's marker for
// generated code.
const header = "// Code generated by `make wiretypes` from the Core's Go types. DO NOT EDIT.\n" +
	"//\n" +
	"// The UI's wire types: the JSON the HTTP API returns. To change one,\n" +
	"// change the Go type and run `make wiretypes`.\n"

// Generate returns the wire types' file: a union and value array for
// each of enums, in their order, and an array of JSON names for each of
// fields; then an interface for each of roots, in their order, for each
// of fields' views, and for every struct they reach, in the order first
// reached. It fails, listing every cause, when a root reaches a type
// with no TypeScript form: a typed string with no Enum, a type with its
// own JSON encoding, or a shape JSON can't carry; or when an Enum's
// list misses one of its type's declared constants.
func Generate(roots []reflect.Type, enums []Enum, fields []Fields) (string, error) {
	g := &generator{
		enums:    map[reflect.Type]Enum{},
		names:    map[string]reflect.Type{},
		reported: map[reflect.Type]bool{},
		sources:  map[string]*source{},
	}
	var out bytes.Buffer
	out.WriteString(header)
	for _, e := range enums {
		g.enums[e.Type] = e
	}
	for _, e := range enums {
		if text := g.enum(e); text != "" {
			out.WriteString("\n" + text)
		}
	}
	var views []Fields
	for _, f := range fields {
		if f.Type.Kind() != reflect.Struct || f.Type.Name() == "" {
			g.fail("field list %s: %s isn't a named struct", f.List, f.Type)
			continue
		}
		views = append(views, f)
		out.WriteString("\n" + fieldList(f))
	}
	for _, t := range roots {
		if t.Kind() != reflect.Struct || t.Name() == "" {
			g.fail("root %s isn't a named struct", t)
			continue
		}
		if !g.ownJSON(t, "the root list") {
			g.reach(t)
		}
	}
	for _, f := range views {
		if !g.ownJSON(f.Type, "field list "+f.List) {
			g.reach(f.Type)
		}
	}
	for len(g.queue) > 0 {
		t := g.queue[0]
		g.queue = g.queue[1:]
		out.WriteString("\n" + g.iface(t))
	}
	if len(g.errs) > 0 {
		return "", errors.Join(g.errs...)
	}
	return out.String(), nil
}

// generator holds one run of Generate.
type generator struct {
	enums map[reflect.Type]Enum
	// names are the TypeScript names taken so far, by the Go type that
	// took each.
	names map[string]reflect.Type
	// queue are the structs reached and not yet written.
	queue []reflect.Type
	// reported are the types already failed on, so each fails once.
	reported map[reflect.Type]bool
	sources  map[string]*source
	errs     []error
}

func (g *generator) fail(format string, args ...any) {
	g.errs = append(g.errs, fmt.Errorf(format, args...))
}

// failOnce fails on t only the first time it is reached.
func (g *generator) failOnce(t reflect.Type, format string, args ...any) {
	if !g.reported[t] {
		g.reported[t] = true
		g.fail(format, args...)
	}
}

// claim takes t's name in the TypeScript file, reporting whether it was
// free, and fails if a different Go type already has it.
func (g *generator) claim(t reflect.Type) bool {
	if other, ok := g.names[t.Name()]; ok {
		if other != t {
			g.failOnce(t, "%s and %s would both be %s in TypeScript", other, t, t.Name())
		}
		return false
	}
	g.names[t.Name()] = t
	return true
}

// reach queues struct t to be written, unless it already is.
func (g *generator) reach(t reflect.Type) {
	if g.claim(t) {
		g.queue = append(g.queue, t)
	}
}

// enum is e's value array and union, after checking the list against
// the type's declared constants.
func (g *generator) enum(e Enum) string {
	t := e.Type
	if !typedString(t) {
		g.fail("value list %s: %s isn't a typed string", e.List, t)
		return ""
	}
	src, err := g.source(t.PkgPath())
	if err != nil {
		g.fail("value list %s: %v", e.List, err)
		return ""
	}
	consts, err := src.constants(t.Name())
	if err != nil {
		g.fail("value list %s: %v", e.List, err)
	}
	for _, c := range consts {
		if !slices.Contains(e.Values, c.value) {
			g.fail("value list %s misses %s's constant %s (%q)", e.List, t, c.name, c.value)
		}
	}
	if !g.claim(t) {
		return ""
	}
	array := screamingSnake(e.List)
	var b strings.Builder
	b.WriteString(comment("", src.typeDoc(t.Name())))
	fmt.Fprintf(&b, "export const %s = [\n", array)
	for _, v := range e.Values {
		fmt.Fprintf(&b, "  %s,\n", quote(v))
	}
	b.WriteString("] as const;\n")
	fmt.Fprintf(&b, "export type %s = (typeof %s)[number];\n", t.Name(), array)
	return b.String()
}

// fieldList is f's array of its view's JSON names, as the Core's
// JSONNames lists them, so it names exactly what a write's changed can.
func fieldList(f Fields) string {
	array := screamingSnake(f.List)
	var b strings.Builder
	fmt.Fprintf(&b, "// %s are %s's JSON names in field order, the order\n", array, f.Type.Name())
	b.WriteString("// a write's Acknowledgement lists them in changed.\n")
	fmt.Fprintf(&b, "export const %s = [\n", array)
	for _, name := range core.JSONNames(f.Type) {
		fmt.Fprintf(&b, "  %s,\n", quote(name))
	}
	b.WriteString("] as const;\n")
	return b.String()
}

// iface is struct t's interface. Its fields are t's JSON names in field
// order, read as the Core's JSONNames reads them; an embedded struct
// with no JSON name is extended instead.
func (g *generator) iface(t reflect.Type) string {
	src, err := g.source(t.PkgPath())
	if err != nil {
		g.fail("%s: %v", t, err)
		return ""
	}
	docs := src.fieldDocs(t.Name())
	var extends []string
	var body strings.Builder
	for f := range t.Fields() {
		at := t.Name() + "." + f.Name
		name, rest, _ := strings.Cut(f.Tag.Get("json"), ",")
		opts := strings.Split(rest, ",")
		switch {
		case name == "-" || !f.IsExported() && !f.Anonymous:
			continue
		case f.Anonymous && name == "" && f.Type.Kind() == reflect.Struct:
			if g.ownJSON(f.Type, at) {
				continue
			}
			if f.Type.Name() == "" {
				g.fail("%s embeds an unnamed struct", at)
				continue
			}
			g.reach(f.Type)
			extends = append(extends, f.Type.Name())
			continue
		case f.Anonymous && name == "" && f.Type.Kind() == reflect.Pointer:
			g.fail("%s embeds a pointer, which the Core's JSONNames doesn't read", at)
			continue
		case name == "":
			name = f.Name
		}
		if slices.Contains(opts, "string") {
			g.fail("%s has the string option, which changes its JSON type", at)
			continue
		}
		optional := f.Type.Kind() == reflect.Pointer ||
			slices.Contains(opts, "omitempty") || slices.Contains(opts, "omitzero")
		typ := g.ts(f.Type, at)
		body.WriteString(comment("  ", docs[f.Name]))
		mark := ""
		if optional {
			mark = "?"
		}
		fmt.Fprintf(&body, "  %s%s: %s;\n", property(name), mark, typ)
	}
	var b strings.Builder
	b.WriteString(comment("", src.typeDoc(t.Name())))
	fmt.Fprintf(&b, "export interface %s ", t.Name())
	if len(extends) > 0 {
		fmt.Fprintf(&b, "extends %s ", strings.Join(extends, ", "))
	}
	b.WriteString("{\n" + body.String() + "}\n")
	return b.String()
}

var (
	timeType       = reflect.TypeFor[time.Time]()
	rawMessageType = reflect.TypeFor[json.RawMessage]()
	jsonMarshaler  = reflect.TypeFor[json.Marshaler]()
	textMarshaler  = reflect.TypeFor[encoding.TextMarshaler]()
)

// ownJSON fails, once per type, if t encodes itself rather than as its
// shape, and reports whether it does. at is the field that reached t.
func (g *generator) ownJSON(t reflect.Type, at string) bool {
	for _, m := range []reflect.Type{jsonMarshaler, textMarshaler} {
		if t.Implements(m) || t.Kind() != reflect.Pointer && reflect.PointerTo(t).Implements(m) {
			method := "MarshalJSON"
			if m == textMarshaler {
				method = "MarshalText"
			}
			g.failOnce(t, "%s (reached by %s) has its own %s, so its shape isn't its JSON; leave it out of the roots", t, at, method)
			return true
		}
	}
	return false
}

// ts is the TypeScript type of Go type t, reached by field at.
func (g *generator) ts(t reflect.Type, at string) string {
	switch t {
	case timeType:
		return "string"
	case rawMessageType:
		return "unknown"
	}
	if t.Kind() == reflect.Pointer {
		return g.ts(t.Elem(), at)
	}
	if g.ownJSON(t, at) {
		return "unknown"
	}
	if strings.Contains(t.Name(), "[") {
		g.failOnce(t, "%s (reached by %s) is generic, which the generator doesn't name", t, at)
		return "unknown"
	}
	if integer(t) || t.Kind() == reflect.Float32 || t.Kind() == reflect.Float64 {
		return "number"
	}
	switch t.Kind() {
	case reflect.Bool:
		return "boolean"
	case reflect.String:
		if !typedString(t) {
			return "string"
		}
		if _, ok := g.enums[t]; !ok {
			g.failOnce(t, "%s (reached by %s) is a typed string with no value list registered in internal/wiretypes", t, at)
		}
		return t.Name()
	case reflect.Slice, reflect.Array:
		if t.Kind() == reflect.Slice && t.Elem().Kind() == reflect.Uint8 {
			return "string" // encoding/json writes []byte as base64
		}
		return g.ts(t.Elem(), at) + "[]"
	case reflect.Map:
		key, value := t.Key(), g.ts(t.Elem(), at)
		switch {
		case typedString(key):
			return fmt.Sprintf("Partial<Record<%s, %s>>", g.ts(key, at), value)
		case key.Kind() == reflect.String || integer(key):
			return fmt.Sprintf("Record<string, %s>", value)
		}
	case reflect.Struct:
		if t.Name() == "" {
			g.fail("%s has an unnamed struct type; give it a name", at)
			return "unknown"
		}
		g.reach(t)
		return t.Name()
	case reflect.Interface:
		return "unknown"
	}
	g.failOnce(t, "%s (reached by %s) has no TypeScript form", t, at)
	return "unknown"
}

// typedString reports whether t is a string type a package declares.
func typedString(t reflect.Type) bool {
	return t.Kind() == reflect.String && t.Name() != "" && t.PkgPath() != ""
}

// integer reports whether t is an integer type, which JSON writes as a
// string when it is a map key.
func integer(t reflect.Type) bool {
	return t.Kind() >= reflect.Int && t.Kind() <= reflect.Uint64
}

// screamingSnake is a Go list name in SCREAMING_SNAKE_CASE, a word
// starting at each capital that follows a lower-case letter, or that
// starts a word after an acronym: CIFailureOptions is CI_FAILURE_OPTIONS.
func screamingSnake(name string) string {
	r := []rune(name)
	var b strings.Builder
	for i, c := range r {
		if i > 0 && unicode.IsUpper(c) &&
			(unicode.IsLower(r[i-1]) || i+1 < len(r) && unicode.IsUpper(r[i-1]) && unicode.IsLower(r[i+1])) {
			b.WriteByte('_')
		}
		b.WriteRune(unicode.ToUpper(c))
	}
	return b.String()
}

// comment is doc as // lines, each indented by indent.
func comment(indent, doc string) string {
	doc = strings.TrimRight(doc, "\n")
	if doc == "" {
		return ""
	}
	var b strings.Builder
	for line := range strings.SplitSeq(doc, "\n") {
		if line == "" {
			b.WriteString(indent + "//\n")
		} else {
			b.WriteString(indent + "// " + line + "\n")
		}
	}
	return b.String()
}

// quote is s as a TypeScript string literal.
func quote(s string) string {
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	_ = enc.Encode(s) // a string always encodes
	return strings.TrimSuffix(b.String(), "\n")
}

// property is a JSON name as a TypeScript property name, quoted unless
// it is an identifier.
func property(name string) string {
	for i, c := range name {
		if !(c == '_' || c == '$' || unicode.IsLetter(c) || i > 0 && unicode.IsDigit(c)) {
			return quote(name)
		}
	}
	return name
}
